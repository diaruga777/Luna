#!/usr/bin/env python3
"""Build the immutable, indexed keyboard catalog from Unicode and FrequencyWords.
The extension queries this SQLite file; it never expands all emoji into Swift objects.
"""
import pathlib, re, sqlite3, urllib.request
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=ROOT/'LunaLibraries/Sources/LunaKeyboardCore/Resources'
OUT.mkdir(parents=True,exist_ok=True)
def get(url):
    return urllib.request.urlopen(url,timeout=60).read().decode('utf8')
p=OUT/'KeyboardCatalog.sqlite'
if p.exists(): p.unlink()
db=sqlite3.connect(p)
db.executescript('''CREATE TABLE glyphs (id INTEGER PRIMARY KEY, text TEXT NOT NULL, name TEXT NOT NULL);
CREATE TABLE keywords (keyword TEXT NOT NULL COLLATE NOCASE, glyph_id INTEGER NOT NULL, PRIMARY KEY(keyword,glyph_id)) WITHOUT ROWID;
CREATE TABLE words (language TEXT NOT NULL, word TEXT NOT NULL, frequency INTEGER NOT NULL, first TEXT NOT NULL,last TEXT NOT NULL,PRIMARY KEY(language,word)) WITHOUT ROWID;
CREATE INDEX word_ends ON words(language,first,last,frequency DESC);''')
data=get('https://www.unicode.org/Public/emoji/latest/emoji-test.txt')
version=re.search(r'# Version: (.+)',data).group(1)
for line in data.splitlines():
    if '; fully-qualified' not in line and '; component' not in line:continue
    match=re.match(r'([0-9A-F ]+)\s*;.*?#\s+\S+\s+E[\d.]+\s+(.+)',line)
    if not match:continue
    text=''.join(chr(int(c,16)) for c in match[1].split());name=match[2]
    id=db.execute('INSERT INTO glyphs(text,name) VALUES(?,?)',(text,name)).lastrowid
    words=re.findall(r'[\w]+',name.lower())
    for key in set(words+[' '.join(words),'_'.join(words),name.lower()]):
        db.execute('INSERT OR IGNORE INTO keywords VALUES(?,?)',(key,id))
extras={'shrug':'¯\\_(ツ)_/¯','tableflip':'(ノ ゜Д゜)ノ ︵ ┻━┻','takemyenergy':'༼ つ ◕_◕ ༽つ','fingerguns':'(☞ﾟ∀ﾟ)☞','ayyy':'(☞ﾟ∀ﾟ)☞','glare':'ಠ_ಠ','rageface':'t(ಠ益ಠt)','crying':'(╥﹏╥)','--':'—','...':'…','1/2':'½','1/3':'⅓','1/4':'¼','3/4':'¾','2/3':'⅔','->':'→','<-':'←','-^':'↑','^-':'↑','-v':'↓','v-':'↓','<->':'↔','~=':'≈','!=':'≠','<=':'≤','>=':'≥','(r)':'®','(c)':'©','tm':'™','heart':'❤️','love':'❤️','smile':'😊','laugh':'😂','lol':'😂','thanks':'🙏','yes':'👍','no':'👎','happy':'😃','sad':'😢','party':'🎉'}
for key,text in extras.items():
    id=db.execute('INSERT INTO glyphs(text,name) VALUES(?,?)',(text,key)).lastrowid
    db.execute('INSERT INTO keywords VALUES(?,?)',(key,id))
for lang in ['en','es','it']:
    raw=get(f'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/{lang}/{lang}_50k.txt')
    count=0
    for line in raw.splitlines():
        word,freq=line.rsplit(' ',1)
        if not word.isalpha() or not 2<=len(word)<=24:continue
        word=word.lower()
        db.execute('INSERT OR IGNORE INTO words VALUES(?,?,?,?,?)',(lang,word,int(freq),word[0],word[-1]))
        count+=1
        if count>=12000:break
(OUT/'Unicode-LICENSE.txt').write_text(get('https://www.unicode.org/license.txt'))
(OUT/'FrequencyWords-Code-LICENSE.txt').write_text(get('https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/LICENSE'))
(OUT/'FrequencyWords-LICENSE.txt').write_text('FrequencyWords content by Hermit Dave, derived from OpenSubtitles 2018.\nThe words table, filtered to 12000 alphabetic entries per language, is distributed under CC BY-SA 4.0.\nhttps://github.com/hermitdave/FrequencyWords\nhttps://creativecommons.org/licenses/by-sa/4.0/\n\n' + get('https://raw.githubusercontent.com/spdx/license-list-data/main/text/CC-BY-SA-4.0.txt'))
(OUT/'CatalogSources.txt').write_text(f'Unicode Emoji {version}, https://www.unicode.org/Public/emoji/latest/emoji-test.txt\nFrequencyWords 2018 en/es/it, top 12000 alphabetic entries, https://github.com/hermitdave/FrequencyWords\nSee adjacent licenses. Generated by scripts/generate_keyboard_catalog.py.\n')
db.commit(); db.execute('VACUUM');print('emoji version',version,'glyphs',db.execute('select count(*) from glyphs').fetchone()[0],'words',db.execute('select count(*) from words').fetchone()[0]);db.close()
