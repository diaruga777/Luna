import Foundation

/// A user-selectable on-device photo-search model. Most are CLIP-style pairs of
/// Core ML encoders (image + text) that map into one shared embedding space, so a
/// text query can be matched against photo embeddings by cosine similarity. One
/// option (`appleVision`) is a non-embedding baseline that uses Apple's built-in
/// on-device image labeling + OCR instead, for comparison.
///
/// CLIP weights are downloaded on demand from Apple's public Core ML MobileCLIP
/// repository on HuggingFace (or bundled, for MobileCLIP2). The architecture is
/// identical across the MobileCLIP variants; they trade size/latency for accuracy.
enum CLIPModel: String, CaseIterable, Sendable {
    case mobileCLIP2S0
    case mobileCLIPS0
    case mobileCLIPS1
    case mobileCLIPS2
    case mobileCLIPBLT
    case appleVision

    /// Where a model's encoders come from.
    enum Source: Sendable {
        /// Downloaded on demand from HuggingFace and compiled at runtime.
        case huggingFace
        /// Shipped in the app bundle (Xcode compiles the bundled .mlpackage to
        /// .mlmodelc at build time). Available only if the (large) model files
        /// were added to the app target; otherwise the model is unavailable.
        case bundled(imageResource: String, textResource: String)
        /// Uses Apple's on-device system frameworks (Vision) — no model files,
        /// no embeddings; search matches recognized labels + OCR text.
        case system
    }

    var source: Source {
        switch self {
        case .mobileCLIPS0, .mobileCLIPS1, .mobileCLIPS2, .mobileCLIPBLT:
            return .huggingFace
        case .mobileCLIP2S0:
            // MobileCLIP2 has no published Core ML export; the encoders are
            // generated by scripts/convert_mobileclip2_coreml.py and bundled.
            return .bundled(imageResource: "clip_image_s0", textResource: "clip_text_s0")
        case .appleVision:
            return .system
        }
    }

    /// HuggingFace repository hosting the Core ML exports.
    static let huggingFaceRepo = "apple/coreml-mobileclip"

    /// Pinned commit SHA for reproducible downloads (so a repo update can't
    /// silently change the model files or layout the app downloads).
    static let huggingFaceRevision = "3e0a7bfb9fe83da8a3efaa3fd8f7df24214bb947"

    /// Dimensionality of the shared embedding space. All MobileCLIP variants
    /// project into a 512-d space; the Vision baseline has no embeddings.
    var embeddingDimension: Int {
        switch self {
        case .appleVision: return 0
        default: return 512
        }
    }

    /// Square pixel size to request when loading a thumbnail to analyze. Core ML
    /// re-resizes to the model's own input via its image constraint, so this is
    /// only the source resolution.
    var imageInputSize: Int { 256 }

    /// Fixed token sequence length the text encoder expects.
    var textContextLength: Int { 77 }

    var displayName: String {
        switch self {
        case .mobileCLIP2S0: return "MobileCLIP2-S0"
        case .mobileCLIPS0: return "MobileCLIP-S0"
        case .mobileCLIPS1: return "MobileCLIP-S1"
        case .mobileCLIPS2: return "MobileCLIP-S2"
        case .mobileCLIPBLT: return "MobileCLIP-B (LT)"
        case .appleVision: return "Apple Vision (on-device)"
        }
    }

    var detail: String {
        switch self {
        case .mobileCLIP2S0: return "Newest · bundled · improved reinforced training"
        case .mobileCLIPS0: return "Fastest · matches ViT-B/16 zero-shot"
        case .mobileCLIPS1: return "Fast · more accurate than S0"
        case .mobileCLIPS2: return "Balanced · beats SigLIP ViT-B/16"
        case .mobileCLIPBLT: return "Largest · highest accuracy"
        case .appleVision: return "Baseline · Apple image labels + OCR, no download"
        }
    }

    /// The `.mlpackage` directory name for the image encoder within the HF repo.
    /// Nil for bundled / system models.
    var imageEncoderPackage: String? {
        switch self {
        case .mobileCLIPS0: return "mobileclip_s0_image.mlpackage"
        case .mobileCLIPS1: return "mobileclip_s1_image.mlpackage"
        case .mobileCLIPS2: return "mobileclip_s2_image.mlpackage"
        case .mobileCLIPBLT: return "mobileclip_blt_image.mlpackage"
        case .mobileCLIP2S0, .appleVision: return nil
        }
    }

    /// The `.mlpackage` directory name for the text encoder within the HF repo.
    /// Nil for bundled / system models.
    var textEncoderPackage: String? {
        switch self {
        case .mobileCLIPS0: return "mobileclip_s0_text.mlpackage"
        case .mobileCLIPS1: return "mobileclip_s1_text.mlpackage"
        case .mobileCLIPS2: return "mobileclip_s2_text.mlpackage"
        case .mobileCLIPBLT: return "mobileclip_blt_text.mlpackage"
        case .mobileCLIP2S0, .appleVision: return nil
        }
    }
}
